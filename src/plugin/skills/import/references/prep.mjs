function usageError(message) {
  process.stderr.write(`prep: ${message}\n${USAGE}\n`);
  process.exit(2);
}

function parseArgs(argv) {
  if (argv[0] === "--list-codex") {
    if (argv.length !== 2)
      usageError("--list-codex needs one repository directory");
    return { listCodex: argv[1] };
  }
  let file;
  let maxAssistantChars = DEFAULT_MAX_ASSISTANT_CHARS;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--max-assistant-chars") {
      const value = argv[++i];
      if (value === undefined || !/^[1-9][0-9]*$/.test(value)) {
        usageError("--max-assistant-chars needs a positive integer");
      }
      maxAssistantChars = Number(value);
    } else if (arg.startsWith("-")) {
      usageError(`unknown option: ${arg}`);
    } else if (file === undefined) {
      file = arg;
    } else {
      usageError(`unexpected argument: ${arg}`);
    }
  }
  if (file === undefined) usageError("missing session file");
  return { file, maxAssistantChars };
}

function redact(text) {
  let out = text;
  for (const [pattern, replacement] of SECRET_PATTERNS) {
    out = out.replace(pattern, replacement);
  }
  return out;
}

function truncate(text, max) {
  const chars = Array.from(text);
  if (chars.length <= max) return text;
  return `${chars.slice(0, max).join("")} [truncated: ${chars.length - max} more characters]`;
}

function stripDroppedBlocks(text) {
  let out = text;
  for (const pattern of DROPPED_BLOCK_PATTERNS) out = out.replace(pattern, "");
  return out.trim();
}

function formatTime(timestamp) {
  const date = new Date(timestamp);
  if (Number.isNaN(date.getTime())) return "";
  return `${date.toISOString().slice(0, 16).replace("T", " ")} UTC`;
}

function queuedPromptText(prompt) {
  if (typeof prompt === "string") return prompt;
  if (!Array.isArray(prompt)) return null;
  const texts = [];
  for (const block of prompt) {
    if (block?.type === "text" && typeof block.text === "string") {
      texts.push(block.text);
    } else if (block?.type === "image") {
      texts.push("[image]");
    }
  }
  return texts.length ? texts.join("\n") : null;
}

function contentBlocks(content) {
  if (typeof content === "string") return [{ type: "text", text: content }];
  return Array.isArray(content) ? content : [];
}

function resultText(content) {
  if (typeof content === "string") return content;
  return contentBlocks(content)
    .filter((block) => block?.type === "text" && typeof block.text === "string")
    .map((block) => block.text)
    .join("\n");
}

function readQuestions(input) {
  const list = Array.isArray(input?.questions) ? input.questions : [];
  return list
    .filter((q) => typeof q?.question === "string")
    .map((q) => ({
      text: q.question,
      multiSelect: q.multiSelect === true,
      options: (Array.isArray(q.options) ? q.options : [])
        .filter((option) => typeof option?.label === "string")
        .map((option) => ({
          label: option.label,
          description:
            typeof option.description === "string" ? option.description : "",
          preview: typeof option.preview === "string" ? option.preview : "",
        })),
    }));
}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function isRecommended(label) {
  const trailing = TRAILING_PARENTHESIS.exec(label);
  if (trailing === null || !RECOMMENDED_WORD.test(trailing[1])) return false;
  return !NEGATED_RECOMMENDATION.test(trailing[1]);
}

function saidAfterDecline(text) {
  const saidAt = text.indexOf(DECLINED_SAID);
  if (saidAt < 0) return "";
  return text.slice(saidAt + DECLINED_SAID.length).trim();
}

function readClarification(said, questions) {
  const listAt = said.indexOf(QUESTIONS_ASKED);
  const list = listAt < 0 ? "" : said.slice(listAt + QUESTIONS_ASKED.length);
  const starts = questions.map((q) => list.indexOf(`"${q.text}"`));
  const partial = questions.map((question, i) => {
    const start = starts[i];
    if (start < 0) return null;
    let end = list.length;
    for (const other of starts) {
      if (other > start && other < end) end = other;
    }
    const segment = list
      .slice(start + question.text.length + 2, end)
      .replace(/\n\s*-\s*$/, "");
    if (segment.includes(NO_ANSWER_PROVIDED)) return null;
    const answer = /Answer:\s*([\s\S]*)$/.exec(segment)?.[1].trim();
    if (!answer) return null;
    return { answer, picked: pickOptions(question, answer), note: "" };
  });
  return { clarify: true, partial };
}

function labelIndex(question, value) {
  if (typeof value !== "string") return -1;
  return question.options.findIndex(
    (option) => option.label === value || option.label.trim() === value.trim(),
  );
}

function matchLabels(text, at, question, closes) {
  const order = question.options
    .map((_, i) => i)
    .sort(
      (a, b) =>
        question.options[b].label.length - question.options[a].label.length,
    );
  const step = (position) => {
    for (const i of order) {
      const label = question.options[i].label;
      if (!label || !text.startsWith(label, position)) continue;
      const after = position + label.length;
      if (closes(text, after)) return { picked: [i], end: after };
      if (question.multiSelect && text.startsWith(", ", after)) {
        const rest = step(after + 2);
        if (rest) return { picked: [i, ...rest.picked], end: rest.end };
      }
    }
    return null;
  };
  return step(at);
}

function pickOptions(question, value) {
  if (Array.isArray(value)) {
    const indexes = value.map((v) => labelIndex(question, v));
    return indexes.length && indexes.every((i) => i >= 0) ? indexes : null;
  }
  const exact = labelIndex(question, value);
  if (exact >= 0) return [exact];
  if (!question.multiSelect || typeof value !== "string") return null;
  const listed = matchLabels(value, 0, question, (s, at) => at === s.length);
  return listed ? listed.picked : null;
}

function readStructured(result, questions) {
  const annotations = isObject(result.annotations) ? result.annotations : {};
  const answers = questions.map((question) => {
    const value = result.answers[question.text];
    const annotation = annotations[question.text];
    const note =
      isObject(annotation) && typeof annotation.notes === "string"
        ? annotation.notes.trim()
        : "";
    if (value === undefined || value === null) return null;
    const answer = Array.isArray(value)
      ? value.filter((v) => typeof v === "string").join(", ")
      : String(value);
    return {
      answer: answer.trim(),
      picked: pickOptions(question, value),
      note,
    };
  });
  return { answers };
}

function closesQuoted(text, at) {
  if (text[at] !== '"') return false;
  return at + 1 === text.length || /[\s,.;)]/.test(text[at + 1]);
}

function firstOf(text, from, markers) {
  const found = markers
    .map((marker) => text.indexOf(marker, from))
    .filter((at) => at >= 0);
  return found.length ? Math.min(...found) : -1;
}

function nextKey(next) {
  return next === undefined ? [] : [`, "${next}"=`];
}

function ownWordsEnd(text, from, next) {
  const quoted = [PREVIEW_MARKER, NOTES_MARKER, ...ANSWER_TERMINATORS].map(
    (marker) => `"${marker}`,
  );
  const end = firstOf(text, from, [
    ...quoted,
    ...nextKey(next).map((key) => `"${key}`),
  ]);
  if (end >= 0) return end;
  const trimmed = text.replace(/\s+$/, "");
  if (trimmed.endsWith('".')) return trimmed.length - 2;
  if (trimmed.endsWith('"')) return trimmed.length - 1;
  return trimmed.length;
}

function tailEnd(text, from, next, extra = []) {
  const end = firstOf(text, from, [
    ...nextKey(next),
    ...ANSWER_TERMINATORS,
    ...extra,
  ]);
  return end >= 0 ? end : text.length;
}

function readTail(text, from, question, picked, next) {
  let position = from;
  let note = "";
  for (;;) {
    if (text.startsWith(PREVIEW_MARKER, position)) {
      position += PREVIEW_MARKER.length;
      const preview =
        picked && picked.length === 1
          ? question.options[picked[0]].preview
          : "";
      const skip = preview
        ? [position, position + 1].find((at) => text.startsWith(preview, at))
        : undefined;
      position =
        skip !== undefined
          ? skip + preview.length
          : tailEnd(text, position, next, [NOTES_MARKER]);
      continue;
    }
    if (text.startsWith(NOTES_MARKER, position)) {
      const start = position + NOTES_MARKER.length;
      position = tailEnd(text, start, next, [PREVIEW_MARKER]);
      note = text.slice(start, position).trim();
      continue;
    }
    return { note, position };
  }
}

function readAnswerText(text, questions) {
  let region = text;
  let said = "";
  const alsoAt = text.indexOf(ALSO_WROTE);
  if (alsoAt >= 0) {
    said = text
      .slice(alsoAt + ALSO_WROTE.length)
      .trim()
      .replace(/^"([\s\S]*)"\.?$/, "$1")
      .trim();
    region = text.slice(0, alsoAt);
  }

  let cursor = 0;
  let found = 0;
  const answers = questions.map((question, i) => {
    const key = `"${question.text}"=`;
    const start = region.indexOf(key, cursor);
    if (start < 0) return null;
    found += 1;
    const next = questions[i + 1]?.text;
    let at = start + key.length;
    if (region.startsWith(NO_SELECTION, at)) {
      cursor = at + NO_SELECTION.length;
      return { answer: "", picked: null, note: "", noSelection: true };
    }
    if (region[at] !== '"') {
      cursor = at;
      return null;
    }
    at += 1;
    const matched = matchLabels(region, at, question, closesQuoted);
    const close = matched ? matched.end : ownWordsEnd(region, at, next);
    const answer = region.slice(at, close).trim();
    const picked = matched ? matched.picked : null;
    const tail = readTail(region, close + 1, question, picked, next);
    cursor = tail.position;
    return { answer, picked, note: tail.note };
  });

  if (found === 0) {
    if (text.startsWith(RESPONDED)) {
      return { responded: true, said: text.slice(RESPONDED.length).trim() };
    }
    return { unparsed: text };
  }
  return {
    answers,
    idle: text.startsWith(IDLE_PREFIX),
    moreQuestions: text.includes(MORE_QUESTIONS),
    said,
  };
}

function readAnswers(raw, questions, toolUseResult) {
  const text = raw.trim();
  if (text.startsWith(TOOL_ERROR)) return { toolError: true };
  if (text.startsWith(DECLINED)) {
    const said = saidAfterDecline(text);
    if (said.startsWith(CLARIFY_PREFIX)) {
      return readClarification(said, questions);
    }
    return { declined: true, said };
  }
  if (isObject(toolUseResult) && isObject(toolUseResult.answers)) {
    return readStructured(toolUseResult, questions);
  }
  const prefix = ANSWER_PREFIXES.find((p) => text.startsWith(p));
  return readAnswerText(
    prefix ? text.slice(prefix.length).trimStart() : text,
    questions,
  );
}

function classify(question, entry) {
  if (!entry.answer) return "the user gave an empty answer";
  if (!entry.picked) {
    return "answered in the user's own words (not one of the options)";
  }
  const picked = entry.picked;
  const recommended = question.options
    .map((option, i) => (isRecommended(option.label) ? i : -1))
    .filter((i) => i >= 0);
  const names = `option${picked.length > 1 ? "s" : ""} ${picked
    .map((i) => i + 1)
    .join(", ")}`;
  if (recommended.length === 0) {
    return `picked ${names} (no option was marked as recommended)`;
  }
  if (picked.every((i) => recommended.includes(i))) {
    return picked.length === 1
      ? "picked the recommended option"
      : `picked ${names}, all of them recommended`;
  }
  const recommendedNames = `option${recommended.length > 1 ? "s" : ""} ${recommended
    .map((i) => i + 1)
    .join(", ")}`;
  return picked.length === 1
    ? `picked ${names}, not the recommended one (recommended: ${recommendedNames})`
    : `picked ${names}, not only the recommended ones (recommended: ${recommendedNames})`;
}

function renderAnswer(lines, question, entry) {
  if (!entry) {
    lines.push("Answer: (no answer in the record)");
    return;
  }
  if (entry.noSelection) {
    lines.push("Answer: (no option selected)");
  } else {
    lines.push(`Answer: ${truncate(redact(entry.answer), MAX_USER_CHARS)}`);
    lines.push(`  -> ${classify(question, entry)}`);
  }
  if (entry.note) {
    lines.push(`User note: ${truncate(redact(entry.note), MAX_USER_CHARS)}`);
  }
}

function renderQuestion(part) {
  const answeredAt = part.answeredAt
    ? `, answered ${formatTime(part.answeredAt)}`
    : "";
  const lines = [
    `### AI asked the user (asked ${formatTime(part.timestamp)}${answeredAt})`,
  ];
  const result = part.result;
  if (result?.idle) {
    lines.push(
      "(the question timed out; the answers below were selected but not submitted)",
    );
  }
  if (result?.moreQuestions) {
    lines.push("(the user asked the AI for more questions)");
  }
  part.questions.forEach((question, i) => {
    if (i > 0 || lines.length > 1) lines.push("");
    const numbering =
      part.questions.length > 1 ? ` ${i + 1} of ${part.questions.length}` : "";
    lines.push(`Question${numbering}: ${redact(question.text)}`);
    if (question.multiSelect)
      lines.push("(more than one option may be picked)");
    lines.push("Options:");
    question.options.forEach((option, n) => {
      const description = option.description
        ? ` - ${truncate(redact(option.description), MAX_OPTION_DESCRIPTION_CHARS)}`
        : "";
      lines.push(`  ${n + 1}. ${redact(option.label)}${description}`);
    });
    if (!result) {
      lines.push("Answer: (no answer in the record)");
    } else if (result.declined) {
      lines.push("Answer: (the user declined to answer the question)");
    } else if (result.clarify) {
      const entry = result.partial[i];
      if (entry) {
        lines.push(
          `Selected before asking to clarify: ${truncate(redact(entry.answer), MAX_USER_CHARS)}`,
        );
        lines.push(`  -> ${classify(question, entry)}`);
      }
    } else if (result.answers) {
      renderAnswer(lines, question, result.answers[i]);
    }
  });
  if (result?.clarify) {
    lines.push("Answer: (the user chose to clarify instead of answering)");
  } else if (result?.toolError) {
    lines.push(
      "Answer: (the question failed with a tool error; there is no answer)",
    );
  } else if (result?.responded) {
    lines.push(
      "Answer: (the user replied in their own words instead of picking)",
    );
  } else if (result?.unparsed !== undefined) {
    lines.push(
      `Answer (as recorded): ${truncate(redact(result.unparsed), MAX_USER_CHARS)}`,
    );
  } else if (!result && part.questions.length === 0) {
    lines.push("Answer: (no answer in the record)");
  }
  if (result?.said) {
    lines.push(`User said: ${truncate(redact(result.said), MAX_USER_CHARS)}`);
  }
  return lines.join("\n");
}

function renderTools(names) {
  const counts = new Map();
  for (const name of names) counts.set(name, (counts.get(name) ?? 0) + 1);
  const summary = [...counts]
    .map(([name, count]) => (count > 1 ? `${name} x${count}` : name))
    .join(", ");
  return `[AI used tools: ${summary}]`;
}

function convert(lines, sessionId, maxAssistantChars) {
  const parts = [];
  const pendingQuestions = new Map();
  const toolNames = new Map();
  let pendingTools = [];
  let skipped = 0;
  let firstTimestamp = "";
  let lastTimestamp = "";
  let directory = "";
  let userMessages = 0;

  const flushTools = () => {
    if (pendingTools.length) {
      parts.push({ kind: "text", text: renderTools(pendingTools) });
      pendingTools = [];
    }
  };

  const handleUserText = (raw, timestamp) => {
    const text = stripDroppedBlocks(raw);
    if (!text) return;
    if (DROPPED_PREFIXES.some((prefix) => text.startsWith(prefix))) return;

    const command = /<command-name>([\s\S]*?)<\/command-name>/.exec(text);
    if (command) {
      const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text);
      const argText = args ? args[1].trim() : "";
      const name = redact(command[1].trim());
      flushTools();
      if (!argText) {
        parts.push({ kind: "text", text: `[the user ran ${name}]` });
        return;
      }
      userMessages += 1;
      parts.push({
        kind: "text",
        text: `### User (${formatTime(timestamp)})\n${name} ${truncate(redact(argText), MAX_USER_CHARS)}`,
      });
      return;
    }

    const shell = /<bash-input>([\s\S]*?)<\/bash-input>/.exec(text);
    if (shell) {
      flushTools();
      parts.push({
        kind: "text",
        text: `[the user ran a shell command: ${truncate(redact(shell[1].trim()), MAX_SHELL_INPUT_CHARS)}]`,
      });
      return;
    }

    flushTools();
    userMessages += 1;
    parts.push({
      kind: "text",
      text: `### User (${formatTime(timestamp)})\n${truncate(redact(text), MAX_USER_CHARS)}`,
    });
  };

  const handleQueuedPrompt = (attachment, timestamp) => {
    if (!isObject(attachment) || attachment.type !== "queued_command") return;
    if (attachment.commandMode !== "prompt") return;
    if (attachment.isMeta === true) return;
    if (attachment.origin != null && attachment.origin.kind !== "human") return;
    const prompt = queuedPromptText(attachment.prompt);
    if (prompt === null) return;
    const text = stripDroppedBlocks(prompt);
    if (!text) return;
    const time =
      timestamp ||
      (typeof attachment.timestamp === "string" ? attachment.timestamp : "");
    flushTools();
    userMessages += 1;
    parts.push({
      kind: "text",
      text: `### User (${formatTime(time)}, sent while the AI was working)\n${truncate(redact(text), MAX_USER_CHARS)}`,
    });
  };

  const handleRejection = (block) => {
    const name = toolNames.get(block.tool_use_id);
    if (name === undefined) return;
    toolNames.delete(block.tool_use_id);
    const rejection = resultText(block.content).trim();
    if (!rejection.startsWith(DECLINED)) return;
    const said = saidAfterDecline(rejection);
    flushTools();
    parts.push({
      kind: "text",
      text: `[the user rejected ${name}]${
        said ? `\nUser said: ${truncate(redact(said), MAX_USER_CHARS)}` : ""
      }`,
    });
  };

  const handleToolResult = (block, entry, timestamp) => {
    const question = pendingQuestions.get(block.tool_use_id);
    if (!question) {
      handleRejection(block);
      return;
    }
    pendingQuestions.delete(block.tool_use_id);
    question.result = readAnswers(
      resultText(block.content),
      question.questions,
      entry.toolUseResult,
    );
    question.answeredAt = timestamp;
  };

  for (const line of lines) {
    if (!line.trim()) continue;
    let entry;
    try {
      entry = JSON.parse(line);
    } catch {
      skipped += 1;
      continue;
    }
    if (!entry || typeof entry !== "object") continue;
    if (entry.isSidechain === true) continue;
    if (!["user", "assistant", "attachment"].includes(entry.type)) continue;

    const timestamp =
      typeof entry.timestamp === "string" ? entry.timestamp : "";
    if (timestamp && formatTime(timestamp)) {
      if (!firstTimestamp) firstTimestamp = timestamp;
      lastTimestamp = timestamp;
    }
    if (!directory && typeof entry.cwd === "string" && entry.cwd) {
      directory = basename(entry.cwd);
    }

    if (entry.type === "attachment") {
      handleQueuedPrompt(entry.attachment, timestamp);
      continue;
    }

    const blocks = contentBlocks(entry.message?.content);
    if (entry.type === "user") {
      if (
        entry.isMeta ||
        entry.isCompactSummary ||
        entry.isVisibleInTranscriptOnly
      ) {
        continue;
      }
      const texts = [];
      for (const block of blocks) {
        if (block?.type === "tool_result") {
          handleToolResult(block, entry, timestamp);
        } else if (block?.type === "text" && typeof block.text === "string") {
          texts.push(block.text);
        } else if (block?.type === "image") {
          texts.push("[image]");
        }
      }
      if (texts.length) handleUserText(texts.join("\n"), timestamp);
      continue;
    }

    if (entry.message?.model === "<synthetic>") continue;
    for (const block of blocks) {
      if (block?.type === "text" && typeof block.text === "string") {
        const text = stripDroppedBlocks(block.text);
        if (!text) continue;
        flushTools();
        parts.push({
          kind: "text",
          text: `### AI\n${truncate(redact(text), maxAssistantChars)}`,
        });
      } else if (block?.type === "tool_use" && typeof block.name === "string") {
        if (block.name === QUESTION_TOOL) {
          flushTools();
          const question = {
            kind: "question",
            timestamp,
            questions: readQuestions(block.input),
            result: null,
          };
          parts.push(question);
          if (typeof block.id === "string")
            pendingQuestions.set(block.id, question);
        } else {
          pendingTools.push(block.name);
          if (typeof block.id === "string") toolNames.set(block.id, block.name);
        }
      }
    }
  }
  flushTools();

  const questionParts = parts.filter((part) => part.kind === "question");
  const asked = questionParts.reduce(
    (sum, part) => sum + part.questions.length,
    0,
  );
  const answered = questionParts
    .filter((part) => part.result?.answers && !part.result.idle)
    .reduce(
      (sum, part) =>
        sum +
        part.result.answers.filter((a) => a !== null && !a.noSelection).length,
      0,
    );
  const period = firstTimestamp
    ? `${formatTime(firstTimestamp)} - ${formatTime(lastTimestamp)}`
    : "(no timestamps)";
  const header = [
    `# Session ${sessionId}`,
    ...(directory ? [`Directory: ${redact(directory)}`] : []),
    `Period: ${period}`,
    `User messages: ${userMessages}`,
    `Questions: ${asked} (answered ${answered}, declined or unanswered ${asked - answered})`,
  ].join("\n");
  const body = parts.map((part) =>
    part.kind === "question" ? renderQuestion(part) : part.text,
  );
  return { output: [header, ...body].join("\n\n") + "\n", skipped };
}

function parseLines(lines) {
  const entries = [];
  let skipped = 0;
  for (const line of lines) {
    if (!line.trim()) continue;
    try {
      const entry = JSON.parse(line);
      if (entry && typeof entry === "object") entries.push(entry);
    } catch {
      skipped += 1;
    }
  }
  return { entries, skipped };
}

function isCodexRecord(entries) {
  return entries.some(
    (entry) => entry.type === "session_meta" && isObject(entry.payload),
  );
}

function codexKind(meta) {
  if (isObject(meta?.source)) return "subagent";
  if (meta?.source === "exec") return "exec";
  return "conversation";
}

const CODEX_KIND_LABELS = {
  conversation: "Codex (conversation with the user)",
  exec: "Codex (codex exec run, not a conversation with the user)",
  subagent: "Codex (sub-agent, not a conversation with the user)",
};

function codexUserText(content) {
  const texts = [];
  for (const block of Array.isArray(content) ? content : []) {
    if (block?.type === "input_image") {
      texts.push("[image]");
      continue;
    }
    if (block?.type !== "input_text" || typeof block.text !== "string")
      continue;
    const text = stripDroppedBlocks(block.text);
    if (!text) continue;
    if (DROPPED_PREFIXES.some((prefix) => text.startsWith(prefix))) continue;
    texts.push(text);
  }
  return texts.join("\n");
}

function codexAssistantText(content) {
  return (Array.isArray(content) ? content : [])
    .filter(
      (block) =>
        block?.type === "output_text" && typeof block.text === "string",
    )
    .map((block) => block.text)
    .join("\n");
}

function convertCodex(entries, sessionId, maxAssistantChars) {
  const parts = [];
  let pendingTools = [];
  let firstTimestamp = "";
  let lastTimestamp = "";
  let directory = "";
  let kind = "conversation";
  let seenMeta = false;
  let userMessages = 0;

  const flushTools = () => {
    if (pendingTools.length) {
      parts.push(renderTools(pendingTools));
      pendingTools = [];
    }
  };

  for (const entry of entries) {
    const payload = isObject(entry.payload) ? entry.payload : {};
    const timestamp =
      typeof entry.timestamp === "string" ? entry.timestamp : "";

    if (entry.type === "session_meta") {
      if (!seenMeta) {
        seenMeta = true;
        kind = codexKind(payload);
        if (typeof payload.cwd === "string" && payload.cwd) {
          directory = basename(payload.cwd);
        }
      }
      continue;
    }
    if (entry.type !== "response_item") continue;
    if (timestamp && formatTime(timestamp)) {
      if (!firstTimestamp) firstTimestamp = timestamp;
      lastTimestamp = timestamp;
    }

    if (payload.type === "message" && payload.role === "user") {
      const text = codexUserText(payload.content);
      if (!text) continue;
      flushTools();
      userMessages += 1;
      parts.push(
        `### User (${formatTime(timestamp)})\n${truncate(redact(text), MAX_USER_CHARS)}`,
      );
    } else if (payload.type === "message" && payload.role === "assistant") {
      const text = stripDroppedBlocks(codexAssistantText(payload.content));
      if (!text) continue;
      flushTools();
      parts.push(`### AI\n${truncate(redact(text), maxAssistantChars)}`);
    } else if (
      (payload.type === "function_call" ||
        payload.type === "custom_tool_call" ||
        payload.type === "local_shell_call") &&
      typeof (payload.name ?? "shell") === "string"
    ) {
      pendingTools.push(payload.name ?? "shell");
    }
  }
  flushTools();

  const period = firstTimestamp
    ? `${formatTime(firstTimestamp)} - ${formatTime(lastTimestamp)}`
    : "(no timestamps)";
  const header = [
    `# Session ${sessionId}`,
    `Client: ${CODEX_KIND_LABELS[kind]}`,
    ...(directory ? [`Directory: ${redact(directory)}`] : []),
    `Period: ${period}`,
    `User messages: ${userMessages}`,
    "Questions: 0 (answered 0, declined or unanswered 0)",
  ].join("\n");
  return [header, ...parts].join("\n\n") + "\n";
}

function codexSessionFiles(root) {
  const found = [];
  const walk = (dir) => {
    let names;
    try {
      names = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of names) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (/^rollout-.*\.jsonl$/.test(entry.name)) found.push(path);
    }
  };
  walk(root);
  return found;
}

function listCodex(repository) {
  const codexHome = process.env.CODEX_HOME || join(homedir(), ".codex");
  let target = resolve(repository);
  try {
    target = realpathSync(target);
  } catch {}
  const rows = [];
  for (const file of codexSessionFiles(join(codexHome, "sessions"))) {
    let entries;
    try {
      entries = parseLines(readFileSync(file, "utf8").split(/\r?\n/)).entries;
    } catch {
      continue;
    }
    const meta = entries.find(
      (entry) => entry.type === "session_meta",
    )?.payload;
    if (!isObject(meta) || codexKind(meta) !== "conversation") continue;
    if (typeof meta.cwd !== "string") continue;
    if (meta.cwd !== target && !meta.cwd.startsWith(target + sep)) continue;
    let first = "";
    for (const entry of entries) {
      const payload = entry.payload;
      if (
        entry.type === "response_item" &&
        isObject(payload) &&
        payload.type === "message" &&
        payload.role === "user"
      ) {
        first = codexUserText(payload.content);
        if (first) break;
      }
    }
    const started = entries.find(
      (entry) => entry.type === "session_meta",
    )?.timestamp;
    rows.push({
      file,
      started: typeof started === "string" ? started : "",
      size: statSync(file).size,
      first: truncate(redact(first.replace(/\s+/g, " ").trim()), 80),
    });
  }
  rows.sort((a, b) =>
    a.started < b.started ? 1 : a.started > b.started ? -1 : 0,
  );
  return rows
    .map(
      (row) =>
        `${row.file}\t${formatTime(row.started) || "(no time)"}\t${Math.ceil(row.size / 1024)} KB\t${row.first}`,
    )
    .join("\n");
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.listCodex !== undefined) {
    const listing = listCodex(args.listCodex);
    process.stdout.write(listing ? `${listing}\n` : "");
    return;
  }
  const { file, maxAssistantChars } = args;
  let source;
  try {
    if (!statSync(file).isFile()) usageError(`not a file: ${file}`);
    source = readFileSync(file, "utf8");
  } catch {
    usageError(`cannot read session file: ${file}`);
  }
  const sessionId = basename(file).replace(/\.jsonl$/, "");
  const lines = source.split(/\r?\n/);
  const parsed = parseLines(lines);
  const { output, skipped } = isCodexRecord(parsed.entries)
    ? {
        output: convertCodex(parsed.entries, sessionId, maxAssistantChars),
        skipped: parsed.skipped,
      }
    : convert(lines, sessionId, maxAssistantChars);
  process.stdout.write(output);
  process.stderr.write(`prep: skipped ${skipped} malformed line(s)\n`);
}

main();
